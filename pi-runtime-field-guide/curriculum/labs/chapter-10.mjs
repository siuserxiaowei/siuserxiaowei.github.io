import assert from 'node:assert/strict';
import { SessionManager } from '@earendil-works/pi-coding-agent';
const user = content => ({ role: 'user', content, timestamp: 0 });
const compacted = SessionManager.inMemory();
const oldId = compacted.appendMessage(user('OLD_RAW_SENTINEL'));
const keptId = compacted.appendMessage(user('continue with the query test'));
const compactId = compacted.appendCompaction('Earlier work chose SQLite.', keptId, 1234);
const projected = JSON.stringify(compacted.buildSessionContext().messages);
assert.equal(compacted.getEntry(oldId).message.content, 'OLD_RAW_SENTINEL');
assert.equal(compacted.getEntry(compactId).firstKeptEntryId, keptId);
assert.ok(projected.includes('Earlier work chose SQLite.'));
assert.ok(projected.includes('continue with the query test'));
assert.ok(!projected.includes('OLD_RAW_SENTINEL'));
const branched = SessionManager.inMemory();
const common = branched.appendMessage(user('shared goal'));
const oldLeaf = branched.appendMessage(user('LEFT_RAW_SENTINEL'));
const summaryId = branched.branchWithSummary(common, 'Approach A was explored.', undefined, true);
const summary = branched.getEntry(summaryId);
assert.equal(summary.parentId, common);
assert.equal(summary.fromId, oldLeaf);
assert.equal(branched.getEntry(oldLeaf).message.content, 'LEFT_RAW_SENTINEL');
const newContext = JSON.stringify(branched.buildSessionContext().messages);
assert.ok(newContext.includes('Approach A was explored.'));
assert.ok(!newContext.includes('LEFT_RAW_SENTINEL'));
console.log(JSON.stringify({ compactionRebuilt: true, branchSummaryLinked: true, rawHistoryPreserved: true }));
